#!/usr/bin/env python3
"""Generate the SurfaceFlinger transaction-code tables from impl/spec/sf_protocol.json.

Writes impl/crates/openink-core/src/sf_codes.rs (a Rust enum) and
impl/java/openink/src/main/java/org/openink/sf/SfCode.java. Both are generated: edit the spec
(or re-run extract_sf_protocol.py), never the outputs. Tests in both languages re-read the JSON.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SPEC = ROOT / "impl/spec/sf_protocol.json"
RUST = ROOT / "impl/crates/openink-core/src/sf_codes.rs"
JAVA = ROOT / "impl/java/openink/src/main/java/org/openink/sf/SfCode.java"
HEADER = "Generated by docs/scripts/gen_sf_codes.py from impl/spec/sf_protocol.json. Do not edit."


def camel(name):
    return "".join(p.capitalize() for p in name.lower().split("_"))


def main():
    codes = json.loads(SPEC.read_text())["codes"]
    rust = [f"// {HEADER}", "",
            "/// Onyx private SurfaceFlinger transaction codes (`android.onyx.ViewUpdateHelper`).",
            "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]", "#[repr(u32)]", "pub enum Code {"]
    rust += [f"    {camel(k)} = {v:#x}," for k, v in codes.items()]
    rust += ["}", "", "impl Code {", "    /// `(spec name, code)` for every code, in spec order.",
             "    pub const ALL: &'static [(&'static str, Code)] = &["]
    rust += [f'        ("{k}", Code::{camel(k)}),' for k in codes]
    rust += ["    ];", "", "    pub fn from_u32(v: u32) -> Option<Code> {",
             "        Self::ALL.iter().find(|(_, c)| *c as u32 == v).map(|(_, c)| *c)", "    }", "}", ""]
    RUST.write_text("\n".join(rust))

    java = [f"// {HEADER}", "package org.openink.sf;", "",
            "/** Onyx private SurfaceFlinger transaction codes. */", "public enum SfCode {"]
    java += [f"    {k}({v:#x})," for k, v in codes.items()]
    java[-1] = java[-1][:-1] + ";"
    java += ["", "    public final int code;", "", "    SfCode(int code) {", "        this.code = code;",
             "    }", "}", ""]
    JAVA.parent.mkdir(parents=True, exist_ok=True)
    JAVA.write_text("\n".join(java))
    print(f"[gen-sf-codes] {len(codes)} codes -> {RUST.relative_to(ROOT)}, {JAVA.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
