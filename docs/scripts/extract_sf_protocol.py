#!/usr/bin/env python3
"""Extract Onyx's private SurfaceFlinger Binder protocol from the decompiled
android.onyx.ViewUpdateHelper into one JSON spec (impl/spec/sf_protocol.json).

For every static method that transacts to SurfaceFlinger it records the transaction code and the
ordered Parcel writes (and reply reads), so the open-source Rust/Java layers are checked against
the same single source instead of hand-copied numbers.

usage: extract_sf_protocol.py <ViewUpdateHelper.java> <out.json>
"""
import json
import re
import sys

CONST = re.compile(r"^\s+public static (?:final )?int ([A-Z][A-Z0-9_]+) = (-?\d+);", re.M)
METHOD = re.compile(r"^    (?:public|private|protected)? ?static [\w<>\[\], ]+? (\w+)\(([^)]*)\) \{", re.M)
WRITE = re.compile(r"\b(data|\w+Data)\.write(\w+)\(([^;]*)\);")
READ = re.compile(r"\breply\.read(\w+)\(")
TRANSACT = re.compile(r"transactData\((\w+),")
DIRECT = re.compile(r"\.transact\((\w+),")


def method_bodies(src):
    """Yield (name, params, body) using brace matching from each method header."""
    for m in METHOD.finditer(src):
        depth, i = 1, m.end()
        while depth and i < len(src):
            depth += {"{": 1, "}": -1}.get(src[i], 0)
            i += 1
        yield m.group(1), m.group(2).strip(), src[m.end():i - 1]


def main():
    src = open(sys.argv[1]).read()
    consts = {k: int(v) for k, v in CONST.findall(src)}
    # Shape, not magnitude: codes live in two ranges (UI_X_* modes are large too, but outside them).
    in_range = lambda v: (v >> 8) == 0xFF00 or 0x100000 <= v < 0x101000
    codes = {k: v for k, v in consts.items() if in_range(v)}
    methods = []
    for name, params, body in method_bodies(src):
        used = TRANSACT.findall(body) + DIRECT.findall(body)
        used = [c for c in used if c in codes]
        if not used:
            continue
        methods.append({
            "method": name,
            "params": params,
            "codes": sorted(set(used)),
            "writes": [f"{kind}({arg.strip()})" for _, kind, arg in WRITE.findall(body)
                       if kind != "InterfaceToken"],
            "reply": READ.findall(body),
        })
    spec = {
        "_source": "android/onyx/ViewUpdateHelper.java (framework.jar, firmware 4.2.1), "
                   "generated by docs/scripts/extract_sf_protocol.py",
        "service": "SurfaceFlinger",
        "interface_token": "android.ui.ISurfaceComposer",
        "codes": dict(sorted(codes.items(), key=lambda kv: kv[1])),
        "constants": {k: v for k, v in sorted(consts.items()) if k not in codes},
        "methods": methods,
    }
    uncalled = sorted(set(codes) - {c for m in methods for c in m["codes"]})
    spec["codes_without_caller"] = uncalled
    with open(sys.argv[2], "w") as f:
        json.dump(spec, f, indent=1)
    print(f"[sf-protocol] {len(codes)} transaction codes, {len(spec['constants'])} other constants, "
          f"{len(methods)} transacting methods, {len(uncalled)} codes with no Java caller")
    if len(codes) < 100 or len(methods) < 50:  # baseline from the first extraction: 112 codes, 112 methods
        sys.exit("[sf-protocol] FAILED: far fewer codes/methods than expected, regex drift?")


if __name__ == "__main__":
    main()
